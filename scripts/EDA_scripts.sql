-- MAGNITUDE EXPLORATION --

-- FIND TOTAL CUSTOMERS BY CONTRIES
SELECT 
COUNTRY,
COUNT(customer_id) AS NOOFCUSTOMERS
FROM GOLD.dim_customers
GROUP BY country
ORDER BY NOOFCUSTOMERS DESC

-- FIND TOTAL CUSTOMERS BY GENDER
SELECT 
GENDER,
COUNT(customer_id) AS NOOFCUST
FROM GOLD.dim_customers
GROUP BY gender

-- FIND TOTAL PRODUCTS BY CATEGORY
SELECT CATEGORY_NAME,
COUNT(DISTINCT product_id) AS NOOFPRODUCTS
FROM GOLD.dim_products
GROUP BY category_name
ORDER BY NOOFPRODUCTS

-- WHAT IS THE AVERAGE COSTS IN EACH CATEGORY
SELECT 
category_name,
AVG(cost) AS AVERAGECOST
FROM GOLD.dim_products
GROUP BY category_name
ORDER BY AVERAGECOST DESC


-- WHAT IS THE TOTAL REVENUE GENERATED FOR EACH CATEGORY
SELECT 
B.category_name,
SUM (A.sales_amount) AS TOTALREVENUE
FROM GOLD.fact_sales A
LEFT JOIN GOLD.dim_products B
ON A.product_key = B.product_key
GROUP BY B.category_name
ORDER BY TOTALREVENUE DESC


-- FIND TOTAL REVENUE THAT IS GENERATED BY EACH CUSTOMER
SELECT 
B.customer_key,
CONCAT(B.FIRST_NAME,' ',B.LAST_NAME) AS FULLNAME,
SUM (A.sales_amount) AS TOTALREVENUE
FROM GOLD.fact_sales A
LEFT JOIN GOLD.dim_customers B
ON A.customer_key=B.customer_key
GROUP BY B.customer_key,CONCAT(B.FIRST_NAME,' ',B.LAST_NAME)
ORDER BY TOTALREVENUE DESC 

-- WHAT IS THE DISTRIBUTION OF SOLD ITEMS ACROSS CONTRIES
SELECT 
B.country,
SUM (A.quantity) AS TOTAL_ITEMS_SOLD
FROM GOLD.fact_sales A
LEFT JOIN GOLD.dim_customers B
ON A.customer_key=B.customer_key
GROUP BY B.country
ORDER BY TOTAL_ITEMS_SOLD DESC 



-- RANKING --
-- WHICH 5 PRODUCTS GENERATE THE HIGHEST REVENUE?
SELECT TOP 5 WITH TIES
B.PRODUCT_NAME,
SUM(A.sales_amount) AS TOTAL_REVENUE
FROM GOLD.fact_sales A
LEFT JOIN GOLD.dim_products B
ON A.product_key = B.product_key
GROUP BY B.product_name
ORDER BY TOTAL_REVENUE DESC


-- WHAT ARE THE 5 WORST PERFORMING PRODUCTS IN TERMS OF SALES
SELECT TOP 5 WITH TIES
B.PRODUCT_NAME,
SUM(A.sales_amount) AS TOTAL_REVENUE
FROM GOLD.fact_sales A
LEFT JOIN GOLD.dim_products B
ON A.product_key = B.product_key
GROUP BY B.product_name
ORDER BY TOTAL_REVENUE ASC

-- FIND THE TOP 10 CUSTOMERS WHO HAVE GENERATED THE HIGHEST REVENUE AND 3 CUSTOMERS WITH THE FEWEST ORDERS PLACED
SELECT TOP 10 
B.customer_key,
CONCAT(B.FIRST_NAME,' ',B.LAST_NAME) AS FULLNAME,
SUM (A.sales_amount) AS TOTALREVENUE
FROM GOLD.fact_sales A
LEFT JOIN GOLD.dim_customers B
ON A.customer_key=B.customer_key
GROUP BY B.customer_key,CONCAT(B.FIRST_NAME,' ',B.LAST_NAME)
ORDER BY TOTALREVENUE DESC 

SELECT 
X.customer_key,
CONCAT(Y.FIRST_NAME,' ',Y.LAST_NAME) AS FULL_NAME, 
COUNT(DISTINCT X.order_number) AS NOOFORDERPLACED
FROM GOLD.fact_sales X
LEFT JOIN GOLD.dim_customers Y
ON X.customer_key = Y.customer_key
GROUP BY X.customer_key,CONCAT(Y.FIRST_NAME,' ',Y.LAST_NAME)
ORDER BY NOOFORDERPLACED ASC



